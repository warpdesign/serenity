#include <LibCrypto/Curves/SECPxxxr1.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

extern "C" void _start()
{
    u8 private_key[32] {};
    private_key[31] = 1;
    u8 expected_public_key[65] {
        0x04,
        0x6b, 0x17, 0xd1, 0xf2, 0xe1, 0x2c, 0x42, 0x47, 0xf8, 0xbc, 0xe6, 0xe5, 0x63, 0xa4, 0x40, 0xf2,
        0x77, 0x03, 0x7d, 0x81, 0x2d, 0xeb, 0x33, 0xa0, 0xf4, 0xa1, 0x39, 0x45, 0xd8, 0x98, 0xc2, 0x96,
        0x4f, 0xe3, 0x42, 0xe2, 0xfe, 0x1a, 0x7f, 0x9b, 0x8e, 0xe7, 0xeb, 0x4a, 0x7c, 0x0f, 0x9e, 0x16,
        0x2b, 0xce, 0x33, 0x57, 0x6b, 0x31, 0x5e, 0xce, 0xcb, 0xb6, 0x40, 0x68, 0x37, 0xbf, 0x51, 0xf5,
    };

    Crypto::Curves::SECP256r1 curve;
    auto public_key = curve.generate_public_key({ private_key, sizeof(private_key) });
    if (public_key.is_error())
        exit(1);
    auto bytes = public_key.value().bytes();
    if (bytes.size() != sizeof(expected_public_key) || memcmp(bytes.data(), expected_public_key, sizeof(expected_public_key)) != 0)
        exit(2);

    puts("p256=ok");
    exit(0);
}
